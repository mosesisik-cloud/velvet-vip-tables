import fs from 'node:fs';
import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {resolveExternal200ReviewedLink, resolveExternal200ReviewedContact, resolveExternal200ReviewedSource} from '../js/external200-reviewed-links.js';

// Compile reviewed evidence, never search results, into the scoped guest fallback.
export function compileExternal200Routes(records, manifest) {
assert.equal(records.length, 200);
assert.equal(new Set(records.map(r => r.restaurantId)).size, 200);
assert.deepEqual(records.map(r=>r.restaurantId).sort(),manifest.records.map(r=>r.restaurantId).sort());
const https = value => { try { const u = new URL(value); return u.protocol === 'https:' && !u.username && !u.password ? u.href : null; } catch { return null; } };
const routes = Object.fromEntries(records.map(r => {
  const official = r.sources.filter(s => s.kind === 'official').map(s => https(s.url)).filter(Boolean);
  const verified = r.identity.status === 'verified';
  const row = {status:r.status, checkedAt:r.followupCheckedAt || '2026-10-16', source:verified ? official.find(source=>resolveExternal200ReviewedSource(r.restaurantId,source)) || null : null};
  if (r.checks.officialExternalLink) {
    assert.ok(verified, `Unverified identity: ${r.restaurantId}`);
    const binding = r.sources.filter(s => s.kind === 'official')
      .map(s => resolveExternal200ReviewedLink(r.restaurantId, s.url, r.bookingUrl)).find(Boolean);
    assert.ok(binding, `Unreviewed source/destination binding: ${r.restaurantId}`);
    row.source = binding.source;
    row.externalUrl = binding.url;
    row.bookingMode = binding.bookingMode || (r.bookingMode === 'request_only' ? 'request_only' : 'unknown');
  }
  if (verified && r.contact?.bookingExplicit === true) {
    const contact = resolveExternal200ReviewedContact(r.restaurantId, r.contact);
    assert.ok(contact && official.includes(contact.source), `Unreviewed contact binding: ${r.restaurantId}`);
    row.contact = contact;
    if (!row.externalUrl) row.source = contact.source;
  }
  if (!verified && row.status === 'closed') throw new Error(`Unverified closure: ${r.restaurantId}`);
  return [r.restaurantId,row];
}));
return routes;
}
if (fileURLToPath(import.meta.url) === path.resolve(process.argv[1] || '')) {
const records = Array.from({length:10}, (_, i) => JSON.parse(fs.readFileSync(`data/external200-group${String(i+1).padStart(2,'0')}.json`, 'utf8').replace(/^\uFEFF/, '')).records).flat();
const manifest = JSON.parse(fs.readFileSync('data/external200-manifest.json'));
const routes = compileExternal200Routes(records, manifest);
const generated = '// Generated by scripts/external200-build-routes.mjs from reviewed decisions.\nexport const external200Routes = ' + JSON.stringify(routes,null,2) + ';\n';
if (process.argv.includes('--check')) assert.equal(fs.readFileSync('js/external200-routes-data.js','utf8').replace(/\r\n/g,'\n'),generated,'Generated routes are stale; rebuild from reviewed decisions.');
else fs.writeFileSync('js/external200-routes-data.js', generated);
console.log(`Compiled ${records.length} scoped booking decisions.`);
}
